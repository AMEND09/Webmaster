// Scans public/ for PDFs and generates the document manifest consumed by the
// Reference page. Runs automatically via predev/prebuild, so the page always
// reflects what's actually published: add or remove a PDF in public/ and
// rebuild — no code changes needed.
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src', 'lib', 'docs.generated.js');

const TITLES = {
  'student-copyright-checklist.pdf': 'Student Copyright Checklist (PDF)',
  'ai-usage.pdf': 'AI Usage Disclosure (PDF)',
};

const prettify = (f) =>
  f
    .replace(/\.pdf$/i, '')
    .replace(/[-_]+/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase()) + ' (PDF)';

const rank = (f) => {
  const i = Object.keys(TITLES).indexOf(f);
  return (i === -1 ? `9:${f}` : `${i}:${f}`);
};

let files = [];
const pub = join(root, 'public');
if (existsSync(pub)) {
  files = readdirSync(pub).filter((f) => f.toLowerCase().endsWith('.pdf'));
}

const docs = files
  .sort((a, b) => (rank(a) < rank(b) ? -1 : 1))
  .map((f) => ({ file: `./${f}`, title: TITLES[f] ?? prettify(f) }));

writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/collect-docs.mjs — do not edit.\n// Rebuilt from public/ on every predev/prebuild.\nexport const docs = ${JSON.stringify(docs, null, 2)};\n`,
);
console.log(`docs manifest: ${docs.length} PDF(s) -> src/lib/docs.generated.js`);
